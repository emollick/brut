export function icon(name, size = 20) {
  const g = G[name];
  if (!g) return '';
  let s = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true">`;
  for (const r of g.r || []) s += `<rect x="${r[0]}" y="${r[1]}" width="${r[2]}" height="${r[3]}"/>`;
  for (const p of g.p || []) s += `<polygon points="${p}"/>`;
  for (const c of g.c || []) s += `<circle cx="${c[0]}" cy="${c[1]}" r="${c[2]}"/>`;
  for (const c of g.k || []) s += `<circle class="ko" cx="${c[0]}" cy="${c[1]}" r="${c[2]}"/>`;
  return s + '</svg>';
}
