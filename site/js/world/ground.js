// The site: a flat building plateau ringed by country, plus the "site plan" – two
// canvases painted with plazas, roads, water, lawns – that the ground shader reads.
import * as THREE from 'three';
import { fbm, smooth, clamp } from '../util.js';

export const SITE_HALF = 512;       // plan texture covers +-512 m
export const BUILD_R = 470;         // buildings stay inside this radius
const PLAN_PX = 2048;

const KIND = {
  paving:  { a: '#ff0000', b: '#000000' },
  asphalt: { a: '#00ff00', b: '#000000' },
  water:   { a: '#0000ff', b: '#000000' },
  lawn:    { a: '#000000', b: '#ff0000' },
  gravel:  { a: '#000000', b: '#0000ff' },
  meadow:  { a: '#000000', b: '#000000' },
};

export const SITES = {
  valley: { name: 'Valley', hills: 1.0, sea: 0, seed: 11 },
  plain:  { name: 'Plain', hills: 0.22, sea: 0, seed: 23 },
  coast:  { name: 'Coast', hills: 0.7, sea: 1, seed: 5 },
  mesa:   { name: 'Plateau', hills: -0.6, sea: 0, seed: 41 },
};

export class Ground {
  constructor(pipe, scene) {
    this.pipe = pipe; this.scene = scene;
    this.site = 'valley';
    this.shapes = [];     // user ground works
    this.aprons = [];     // paving under buildings, regenerated by the city
    this.cvA = document.createElement('canvas'); this.cvB = document.createElement('canvas');
    this.cvA.width = this.cvA.height = this.cvB.width = this.cvB.height = PLAN_PX;
    this.cxA = this.cvA.getContext('2d', { willReadFrequently: false }); this.cxB = this.cvB.getContext('2d');
    const mkT = (cv) => { const t = new THREE.CanvasTexture(cv); t.flipY = false; t.generateMipmaps = true; t.minFilter = THREE.LinearMipmapLinearFilter; t.magFilter = THREE.LinearFilter; t.anisotropy = 8; t.wrapS = t.wrapT = THREE.ClampToEdgeWrapping; return t; };
    this.texA = mkT(this.cvA); this.texB = mkT(this.cvB);
    pipe.U.uPlanA.value = this.texA; pipe.U.uPlanB.value = this.texB;
    pipe.U.uSite.value.x = SITE_HALF;
    // low-res copy of the plan for the simulations (people, wind, sun)
    this.simN = 512;
    this.simCv = document.createElement('canvas'); this.simCv.width = this.simCv.height = this.simN;
    this.simCx = this.simCv.getContext('2d', { willReadFrequently: true });
    this.simA = null; this.simB = null;
    this.mesh = null; this.sea = null;
    this.hasWater = false;
    this.dirty = true;
    this.build();
  }
  heightAt(x, z) {
    const S = SITES[this.site];
    const r = Math.hypot(x, z);
    const k = smooth(700, 4200, r);
    if (k <= 0) return 0;
    const s = S.seed * 13.7;
    let h;
    if (S.hills < 0) {                       // plateau: the land falls away on every side
      h = -smooth(640, 1500, r) * 120 / Math.max(k, 0.05) + fbm(x * 0.0016 + s, z * 0.0016, 4) * 60;
    } else {
      h = (fbm(x * 0.00026 + s, z * 0.00026 - s, 5) - 0.4) * 1100;
      h += (fbm(x * 0.0019 + 9, z * 0.0019 + 3, 3) - 0.4) * 70;
      h = Math.max(h, -6) * S.hills + (fbm(x * 0.006, z * 0.006, 2) - 0.5) * 6;
    }
    if (S.sea) { const sea = smooth(420, 1100, z + (fbm(x * 0.0012, 7.7, 3) - 0.5) * 420); h = h * (1 - sea) - sea * 40 / Math.max(k, 0.05); }
    return h * k;
  }
  build() {
    if (this.mesh) { this.pipe.remove(this.mesh); this.scene.remove(this.mesh); this.mesh.geometry.dispose(); }
    const radii = [0];
    for (let r = 30; r < 14000; r *= 1.075) radii.push(r);
    const seg = 192, pos = [], nrm = [], idx = [];
    const H = (x, z) => this.heightAt(x, z);
    for (let i = 0; i < radii.length; i++) {
      for (let j = 0; j <= seg; j++) {
        const a = (j / seg) * Math.PI * 2, x = Math.cos(a) * radii[i], z = Math.sin(a) * radii[i];
        const y = H(x, z);
        pos.push(x, y, z);
        const e = Math.max(4, radii[i] * 0.03);
        const dx = H(x + e, z) - H(x - e, z), dz = H(x, z + e) - H(x, z - e);
        const n = new THREE.Vector3(-dx, 2 * e, -dz).normalize();
        nrm.push(n.x, n.y, n.z);
      }
    }
    const W = seg + 1;
    for (let i = 0; i < radii.length - 1; i++) for (let j = 0; j < seg; j++) {
      const a = i * W + j, b = a + 1, c = a + W, d = c + 1;
      idx.push(a, b, c, b, d, c);
    }
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    g.setAttribute('normal', new THREE.Float32BufferAttribute(nrm, 3));
    g.setIndex(idx);
    const m = this.mesh = new THREE.Mesh(g, this.pipe.placeholder);
    m.userData.kind = 'ground'; m.frustumCulled = false;
    this.scene.add(m); this.pipe.add(m);
    this.dirty = true;
  }
  setSite(name) { if (SITES[name]) { this.site = name; this.build(); } }

  // ---- site plan ----
  _px(v) { return (v / (SITE_HALF * 2) + 0.5) * PLAN_PX; }
  _path(cx, s) {
    const P = (v) => this._px(v), k = PLAN_PX / (SITE_HALF * 2);
    cx.beginPath();
    if (s.t === 'rect') {
      cx.save(); cx.translate(P(s.x), P(s.z)); cx.rotate(-(s.rot || 0));
      const r = Math.min((s.r || 0) * k, s.w * k / 2, s.d * k / 2);
      if (r > 0 && cx.roundRect) cx.roundRect(-s.w * k / 2, -s.d * k / 2, s.w * k, s.d * k, r); else cx.rect(-s.w * k / 2, -s.d * k / 2, s.w * k, s.d * k);
      cx.restore();
    } else if (s.t === 'disc') {
      cx.ellipse(P(s.x), P(s.z), s.rx * k, (s.rz || s.rx) * k, -(s.rot || 0), 0, Math.PI * 2);
    } else if (s.t === 'poly' || s.t === 'line') {
      const p = s.pts;
      cx.moveTo(P(p[0]), P(p[1]));
      for (let i = 2; i < p.length; i += 2) cx.lineTo(P(p[i]), P(p[i + 1]));
      if (s.t === 'poly') cx.closePath();
    }
  }
  _draw(s) {
    const K = KIND[s.k] || KIND.paving, k = PLAN_PX / (SITE_HALF * 2);
    for (const [cx, col] of [[this.cxA, K.a], [this.cxB, K.b]]) {
      this._path(cx, s);
      if (s.t === 'line') { cx.strokeStyle = col; cx.lineWidth = s.w * k; cx.lineCap = s.cap || 'round'; cx.lineJoin = 'round'; cx.stroke(); }
      else { cx.fillStyle = col; cx.fill(); }
    }
    if (s.t === 'line' && s.k === 'asphalt' && s.w >= 6) {    // centre line
      const cx = this.cxB;
      this._path(cx, s);
      cx.strokeStyle = '#00ff00'; cx.lineWidth = 0.22 * k; cx.setLineDash([3 * k, 4.5 * k]); cx.lineCap = 'butt'; cx.stroke(); cx.setLineDash([]);
    }
    if (s.k === 'water') this.hasWater = true;
  }
  redraw() {
    for (const cx of [this.cxA, this.cxB]) { cx.setTransform(1, 0, 0, 1, 0, 0); cx.globalCompositeOperation = 'source-over'; cx.fillStyle = '#000'; cx.fillRect(0, 0, PLAN_PX, PLAN_PX); }
    this.hasWater = false;
    for (const s of this.aprons) this._draw(s);
    for (const s of this.shapes) this._draw(s);
    this.texA.needsUpdate = true; this.texB.needsUpdate = true;
    this.simCx.drawImage(this.cvA, 0, 0, this.simN, this.simN);
    this.simA = this.simCx.getImageData(0, 0, this.simN, this.simN).data;
    this.simCx.drawImage(this.cvB, 0, 0, this.simN, this.simN);
    this.simB = this.simCx.getImageData(0, 0, this.simN, this.simN).data;
    this.dirty = false;
    this.pipe.reflWanted = this.hasWater;
    this.pipe.invalidate();
  }
  // what is underfoot at (x,z): 0 meadow, 1 paving, 2 asphalt, 3 water, 4 lawn, 5 gravel
  surfaceAt(x, z) {
    if (!this.simA) return 0;
    const n = this.simN, i = clamp(Math.floor((x / (SITE_HALF * 2) + 0.5) * n), 0, n - 1), j = clamp(Math.floor((z / (SITE_HALF * 2) + 0.5) * n), 0, n - 1);
    const o = (j * n + i) * 4, A = this.simA, B = this.simB;
    if (A[o + 2] > 127) return 3; if (A[o + 1] > 127) return 2; if (A[o] > 127) return 1; if (B[o] > 127) return 4; if (B[o + 2] > 127) return 5;
    return 0;
  }
}
